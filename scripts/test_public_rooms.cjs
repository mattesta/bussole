const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ window: {}, Date });
for (const file of ['round-timer.js','scoring.js','public-rooms.js','explorers.js']) vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const rooms = context.window.BussolePublicRooms;
const now = 100000;
const entry = (count, updatedAt = now, phase = 'lobby') => ({ count, updatedAt, phase, createdAt: 1 });
assert.equal(rooms.candidates({ AAAAAA: entry(2), BBBBBB: entry(7), CCCCCC: entry(8), DDDDDD: entry(4, 0), EEEEEE: entry(3, now, 'aiming'), FFFFFF: entry(0) }, now).map(([code]) => code).join(','), 'BBBBBB,AAAAAA');
assert.equal(rooms.canClaim({ uid: 'a', claimedAt: now }, 'b', { a: { connected: true } }, now), false);
assert.equal(rooms.canClaim({ uid: 'a', claimedAt: now }, 'b', { a: { connected: false, lastSeenAt: now - 1000 } }, now), false);
assert.equal(rooms.canClaim({ uid: 'a', claimedAt: now }, 'b', { a: { connected: false, lastSeenAt: now - 31000 } }, now), true);
assert.equal(rooms.canClaim(null, 'b', {}, now), true);
assert.equal(rooms.canClaim({ uid: 'pending', claimedAt: now - 100 }, 'b', {}, now), false);
assert.equal(rooms.canClaim({ uid: 'expired', claimedAt: now - 31000 }, 'b', {}, now), true);
const full = Object.fromEntries([...Array(8)].map((_, i) => [i, { connected: true }]));
assert.equal(rooms.shouldAutoStart({ visibility: 'public', phase: 'lobby', round: 0 }, full, now), true);
assert.equal(rooms.shouldAutoStart({ visibility: 'private', phase: 'lobby', round: 0 }, full, now), false);
assert.equal(rooms.shouldAutoStart({ visibility: 'public', phase: 'aiming', round: 0 }, full, now), false);
assert.equal(rooms.shouldAutoStart({ visibility: 'public', phase: 'lobby', round: 2 }, full, now), false);
assert.equal(rooms.shouldAutoStart({ visibility: 'public', phase: 'lobby', round: 2, matchStartRound: 2 }, full, now), true);
assert.match(rooms.summary({ mode: 'medium', mapStyle: '3d', timerEnabled: true, timerSeconds: 3, scoreGoal: 5000 }), /3D Globe · Normal · 3 s timer · 5000 points/);
const catalogue = context.window.BussoleExplorers.catalogue;
assert.equal(catalogue.length, 8);
for (const explorer of catalogue) { assert.ok(explorer.text.length > 150); assert.ok(explorer.article); }
const elements = Object.fromEntries(['explorerDialog','explorerTitle','explorerBiography','explorerWikipedia'].map(id => [id, {}]));
elements.explorerDialog.showModal = function() { this.open = true; };
elements.explorerDialog.close = function() { this.open = false; };
context.document = { getElementById(id) { return elements[id]; } };
context.window.BussoleExplorers.open(2, {});
assert.equal(elements.explorerTitle.textContent, 'Nellie Bly');
assert.equal(elements.explorerWikipedia.href, 'https://en.wikipedia.org/wiki/Nellie_Bly');
assert.equal(elements.explorerDialog.open, true);
context.window.BussoleExplorers.close(); assert.equal(elements.explorerDialog.open, false);
console.log('Public matching, full/expired/started filters, presence grace, auto-start, settings and explorer dialogs passed.');
